"""
Read-only evaluation of the EXISTING Federated Learning global model.

This script does NOT:
- retrain the model
- write or overwrite global_model.pkl
- write or overwrite preprocessing.pkl
- change prediction.py, federated_learning.py, or the marketplace API

It only loads the saved model, predicts on data/paddy_dataset.csv,
prints MAE / RMSE / R2 / MAPE, and writes RESULTS.md next to this file.
"""

from __future__ import annotations

import pickle
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score,
)

FL_DIR = Path(__file__).resolve().parents[2] / "fl"
MODELS_DIR = FL_DIR / "models"
DATA_PATH = FL_DIR / "data" / "paddy_dataset.csv"
MODEL_PATH = MODELS_DIR / "global_model.pkl"
PREPROCESS_PATH = MODELS_DIR / "preprocessing.pkl"
RESULTS_PATH = Path(__file__).resolve().parent / "RESULTS.md"


def load_saved_artifacts():
    if not MODEL_PATH.exists() or not PREPROCESS_PATH.exists():
        raise FileNotFoundError(
            "Missing FL model files. Expected:\n"
            f"  {MODEL_PATH}\n"
            f"  {PREPROCESS_PATH}\n"
            "This script will not train or replace them."
        )

    with MODEL_PATH.open("rb") as handle:
        model = pickle.load(handle)

    with PREPROCESS_PATH.open("rb") as handle:
        preprocess = pickle.load(handle)

    required_model = {"weights", "bias"}
    required_pre = {
        "district_encoder",
        "paddy_encoder",
        "season_encoder",
        "scaler",
    }
    if not required_model.issubset(model):
        raise ValueError("global_model.pkl does not contain weights and bias")
    if not required_pre.issubset(preprocess):
        raise ValueError("preprocessing.pkl is missing encoder/scaler objects")

    return model, preprocess


def predict_with_saved_model(df: pd.DataFrame, model, preprocess) -> np.ndarray:
    district = preprocess["district_encoder"].transform(df["district"])
    paddy = preprocess["paddy_encoder"].transform(df["paddyType"])
    season = preprocess["season_encoder"].transform(df["season"])

    features = pd.DataFrame(
        {
            "district": district,
            "paddyType": paddy,
            "season": season,
            "quantity": df["quantity"],
        }
    )
    scaled = preprocess["scaler"].transform(features)
    predicted = np.dot(scaled, model["weights"]) + model["bias"]
    return np.asarray(predicted, dtype=float).reshape(-1)


def compute_metrics(actual: np.ndarray, predicted: np.ndarray) -> dict[str, float]:
    mae = float(mean_absolute_error(actual, predicted))
    rmse = float(mean_squared_error(actual, predicted) ** 0.5)
    r2 = float(r2_score(actual, predicted))
    mape = float(np.mean(np.abs((actual - predicted) / actual)) * 100)
    return {
        "n_samples": int(len(actual)),
        "mean_actual": float(np.mean(actual)),
        "mean_predicted": float(np.mean(predicted)),
        "mae": mae,
        "rmse": rmse,
        "r2": r2,
        "mape": mape,
    }


def write_results(metrics: dict[str, float]) -> None:
    RESULTS_PATH.write_text(
        f"""# FL saved-model evaluation metrics

Date: generated by `evaluate_saved_fl_model.py`  
Model: existing `fl/models/global_model.pkl` (not retrained)  
Data: `fl/data/paddy_dataset.csv`  
Mode: **read-only**. Product files were not changed.

## What this measures

The marketplace FL feature predicts a **paddy price (Rs/kg)**. That is regression, not classification. The correct metrics are MAE, RMSE, R2, and MAPE. A confusion matrix is not used.

These numbers are **in-sample**: the saved global model is scored on the same dataset file that exists in the project. They are not a held-out production test of live harvests.

## Results

| Metric | Value | Meaning in one line |
|---|---|---|
| Samples | {metrics["n_samples"]} | Number of rows in the dataset |
| Mean actual price | {metrics["mean_actual"]:.4f} Rs/kg | Average true price in the CSV |
| Mean predicted price | {metrics["mean_predicted"]:.4f} Rs/kg | Average price the saved model predicted |
| **MAE** | **{metrics["mae"]:.4f}** | Average absolute error in Rs/kg |
| **RMSE** | **{metrics["rmse"]:.4f}** | Error that penalises large mistakes more |
| **R2** | **{metrics["r2"]:.4f}** | 1 = perfect, 0 = no better than predicting the mean |
| **MAPE** | **{metrics["mape"]:.4f}%** | Average error as a percent of the true price |

## How to re-run (does not change the app)

```text
python c03-marketplace/testing/fl_evaluation/evaluate_saved_fl_model.py
```
""",
        encoding="utf-8",
    )


def main() -> None:
    model, preprocess = load_saved_artifacts()

    df = pd.read_csv(DATA_PATH)
    df["district"] = df["district"].astype(str).str.strip().str.lower()
    df["paddyType"] = df["paddyType"].astype(str).str.strip().str.lower()
    df["season"] = df["season"].astype(str).str.strip().str.lower()

    predicted = predict_with_saved_model(df, model, preprocess)
    actual = df["price"].to_numpy(dtype=float)
    metrics = compute_metrics(actual, predicted)
    write_results(metrics)

    print("=== FL global model evaluation (read-only) ===")
    print(f"Model file : {MODEL_PATH}")
    print(f"Data file  : {DATA_PATH}")
    print(f"Samples    : {metrics['n_samples']}")
    print(f"Mean actual     : {metrics['mean_actual']:.4f} Rs/kg")
    print(f"Mean predicted  : {metrics['mean_predicted']:.4f} Rs/kg")
    print(f"MAE  : {metrics['mae']:.4f} Rs/kg")
    print(f"RMSE : {metrics['rmse']:.4f} Rs/kg")
    print(f"R2   : {metrics['r2']:.4f}")
    print(f"MAPE : {metrics['mape']:.4f} %")



if __name__ == "__main__":
    main()
