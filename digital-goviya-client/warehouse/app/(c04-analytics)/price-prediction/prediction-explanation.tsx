import {
  useFonts,
  Poppins_800ExtraBold,
  Poppins_700Bold,
  Poppins_600SemiBold,
  Poppins_500Medium,
} from "@expo-google-fonts/poppins";
import type { PredictionApiResponse } from "./prediction-result";

function generatedByMeta(source: string) {
  const s = source.toLowerCase();
  if (s === "llm") return { label: "Generated by AI", icon: "sparkles" as const };
  if (s === "shap") return { label: "Generated by SHAP", icon: "cog" as const };
  return { label: `Generated by ${source}`, icon: "hardware-chip" as const };
}

export default function PredictionExplanationScreen() {
  const { data } = useLocalSearchParams<{ data: string }>();
  const result: PredictionApiResponse | null = data ? JSON.parse(data) : null;

  const [fontsLoaded] = useFonts({
    Poppins_800ExtraBold,
    Poppins_700Bold,
    Poppins_600SemiBold,
    Poppins_500Medium,
  });

  const fade = useRef(new Animated.Value(0)).current;
  const rise = useRef(new Animated.Value(16)).current;

  useEffect(() => {
    if (!fontsLoaded) return;
    Animated.parallel([
      Animated.timing(fade, { toValue: 1, duration: 450, useNativeDriver: true }),
      Animated.timing(rise, { toValue: 0, duration: 450, useNativeDriver: true }),
    ]).start();
  }, [fontsLoaded]);

  if (!fontsLoaded || !result) return null;

  const { explanation, prediction } = result;
  const generatedBy = generatedByMeta(explanation.generated_by);

  return (
    <View style={styles.screen}>
      <LinearGradient
        colors={["#0A331D", "#12522E", "#0B3B22"]}
        start={{ x: 0, y: 0 }}
        end={{ x: 0, y: 1 }}
        style={styles.heroBg}
      />

      <SafeAreaView style={styles.safe}>
        {/* Hero */}
        <View style={styles.hero}>
          <TouchableOpacity
            style={styles.backBtn}
            onPress={() => router.back()}
            hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }}
          >
            <Ionicons name="chevron-back" size={20} color="white" />
          </TouchableOpacity>

          <View style={styles.eyebrowPill}>
            <Ionicons name="bulb" size={11} color="#F5C542" />
            <Text style={styles.eyebrow}>AI EXPLANATION</Text>
          </View>

          <Text style={styles.heroTitle}>Why this price?</Text>
          <Text style={styles.heroSub}>
            {prediction.district} · {prediction.date}
          </Text>
        </View>

        {/* Sheet */}
        <Animated.View
          style={[styles.sheet, { opacity: fade, transform: [{ translateY: rise }] }]}
        >
          <View style={styles.sheetHandle} />

          <ScrollView
            style={{ flex: 1 }}
            contentContainerStyle={styles.scrollContent}
            showsVerticalScrollIndicator={false}
          >
            {/* Highlighted headline + explanation card */}
            <LinearGradient
              colors={["#F0FDF4", "#DCFCE7"]}
              start={{ x: 0, y: 0 }}
              end={{ x: 1, y: 1 }}
              style={styles.highlightCard}
            >
              <View style={styles.generatedByPill}>
                <Ionicons name={generatedBy.icon} size={12} color="#0B3B22" />
                <Text style={styles.generatedByText}>{generatedBy.label}</Text>
              </View>

              <Text style={styles.headline}>{explanation.headline}</Text>

              <View style={styles.quoteBar} />
              <Text style={styles.explanationText}>{explanation.explanation}</Text>
            </LinearGradient>

            {/* Key factors */}
            {explanation.key_factors.length > 0 && (
              <View style={styles.factorsSection}>
                <Text style={styles.sectionTitle}>Key Factors</Text>
                {explanation.key_factors.map((factor, i) => (
                  <View key={i} style={styles.factorRow}>
                    <View style={styles.factorBullet}>
                      <Ionicons name="checkmark" size={13} color="#15803D" />
                    </View>
                    <Text style={styles.factorText}>{factor}</Text>
                  </View>
                ))}
              </View>
            )}
          </ScrollView>
        </Animated.View>
      </SafeAreaView>
    </View>
  );
}

